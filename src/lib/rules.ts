// Копия правил из api/check.ts — работает, если сервер недоступен (демо не ломается).
type Flag = { quote: string; why: string }
export type CheckResult = { risk: number; verdict: 'опасно' | 'подозрительно' | 'похоже безопасно'; scheme: string; flags: Flag[]; actions: string[]; simple: string; fallback?: boolean }
const RULES: { re: RegExp; why: string; w: number }[] = [
  { re: /код[а-я]*\s*(из|в)?\s*(смс|sms)|смс[- ]?код|продиктуйте код|назовите код/i, why: 'Код из СМС не просит ни один банк — это ключ к вашему счёту.', w: 40 },
  { re: /служб[а-я]* безопасности|нацбанк|национальн[а-я]* банк/i, why: 'Мошенники часто представляются службой безопасности или Нацбанком.', w: 30 },
  { re: /переведи|переведите|перевод[а-я]* на|безопасный сч[её]т/i, why: 'Просьба перевести деньги — главная цель мошенника.', w: 25 },
  { re: /срочно|немедленно|в течение \d+ минут|действует \d+ минут|осталось \d+ мест/i, why: 'Давление временем мешает подумать.', w: 15 },
  { re: /инвестиц|пассивн[а-я]* доход|\d+\s*% в месяц|гарантированн[а-я]* доход/i, why: 'Гарантированный высокий доход — признак финансовой пирамиды.', w: 30 },
  { re: /доход/i, why: 'Обещание лёгкого дохода — частая приманка.', w: 10 },
  { re: /ссылк|https?:\/\/|\[\.\]|\.top\b|\.click\b/i, why: 'Ссылка может вести на поддельный сайт, который крадёт данные карты.', w: 20 },
  { re: /данные карты|cvv|cvc|номер карты/i, why: 'Данные карты нельзя вводить по ссылке из переписки.', w: 30 },
  { re: /никому не говори|папе не говори|не сообщайте|не говорите/i, why: 'Просьба держать в секрете — чтобы вас некому было остановить.', w: 20 },
  { re: /с чужого номера|телефон разбился|я в беде|попал в неприятност/i, why: 'Классика «мама, я в беде»: перезвоните родному на его старый номер.', w: 30 },
  { re: /кредит/i, why: 'Тема «на вас оформляют кредит» — частый повод для паники.', w: 15 },
]

export function fallbackCheck(text: string): CheckResult {
  const flags: Flag[] = []
  let score = 0
  for (const r of RULES) {
    const m = text.match(r.re)
    if (m) {
      score += r.w
      if (!flags.some((f) => f.quote.toLowerCase() === m[0].toLowerCase())) flags.push({ quote: m[0], why: r.why })
    }
  }
  const risk = Math.min(98, score)
  const verdict = risk >= 70 ? 'опасно' : risk >= 35 ? 'подозрительно' : 'похоже безопасно'
  const danger = risk >= 35
  return {
    risk,
    verdict,
    scheme: danger ? 'Возможное мошенничество (проверка по правилам)' : 'Обычное сообщение',
    flags,
    actions: danger
      ? ['Ничего не переводите и не называйте коды', 'Положите трубку и перезвоните в банк по номеру на карте', 'Покажите сообщение близким']
      : ['Признаков обмана не найдено', 'Всё равно не сообщайте коды из СМС', 'Сомневаетесь — спросите близких'],
    simple: danger ? 'Похоже на обман: ничего не переводите и посоветуйтесь с близкими.' : 'Похоже на обычное сообщение, но коды из СМС никому не говорите.',
    fallback: true,
  }
}
